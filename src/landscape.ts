export function paintLandscape(ctx: CanvasRenderingContext2D, view: Camera): void {
  const ground = view.height / 2 + view.y * view.zoom;
  if (ground > view.height + 170 * view.zoom) return;
  const halfWidth = view.width / (2 * view.zoom);
  const left = view.x - halfWidth;
  const right = view.x + halfWidth;

  ctx.save();
  ctx.translate(-left * view.zoom, ground);
  ctx.scale(view.zoom, view.zoom);
  for (const section of sections) {
    if (section.right < left || section.left > right) continue;
    for (const hill of section.hills) {
      ctx.fillStyle = hill.color;
      ctx.fill(hill.path);
    }
  }
  for (const grove of groves) {
    for (const [x, y, scale] of grove.trees) {
      const crown = 15 * scale;
      if (x + crown < left || x - crown > right) continue;
      ctx.save();
      ctx.translate(x, y);
      ctx.scale(scale, scale);
      ctx.fillStyle = grove.color;
      ctx.fill(grove.path);
      if ('accent' in grove) {
        ctx.fillStyle = grove.accent;
        ctx.fill(fruit);
      }
      ctx.restore();
    }
  }
  ctx.fillStyle = '#2fa779';
  const grassTop = ground - view.zoom;
  if (grassTop < view.height) ctx.fillRect(left, -1, right - left, (view.height - grassTop) / view.zoom);
  ctx.fill(foreground);
  ctx.fillStyle = '#279b73';
  ctx.fill(grassPatches);
  ctx.restore();
}
